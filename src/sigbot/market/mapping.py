class Party(StrEnum):
    D = "D"
    R = "R"
    I = "I"  # noqa: E741


class Kind(StrEnum):
    CTRL = "CTRL"
    SEN = "SEN"
    GOV = "GOV"
    HOUSE = "HOUSE"


class Outcome(msgspec.Struct, frozen=True, gc=False):
    party: Party
    sig_market_id: str
    sig_exchange_id: str
    sig_title: str
    pm_tokens: tuple[str, ...] = ()
    pm_names: tuple[str, ...] = ()
    kalshi_tickers: tuple[str, ...] = ()
    kalshi_names: tuple[str, ...] = ()


class Unlisted(msgspec.Struct, frozen=True, gc=False):
    """An external outcome (usually an independent) with no SIG market."""

    label: str
    pm_tokens: tuple[str, ...] = ()
    kalshi_tickers: tuple[str, ...] = ()


class Race(msgspec.Struct, frozen=True, gc=False):
    key: str
    kind: Kind
    name: str
    outcomes: tuple[Outcome, ...]
    exhaustive: bool
    state: str | None = None
    district: int | None = None
    flags: tuple[str, ...] = ()
    unlisted: tuple[Unlisted, ...] = ()
    pm_event: str | None = None
    kalshi_event: str | None = None


class Mapping(msgspec.Struct):
    generated_at: str
    tournament_slug: str
    races: list[Race]

    def by_exchange(self) -> dict[str, tuple[Race, Outcome]]:
        return {o.sig_exchange_id: (r, o) for r in self.races for o in r.outcomes}

    def pm_tokens(self) -> set[str]:
        tokens = {t for r in self.races for o in r.outcomes for t in o.pm_tokens}
        tokens.update(t for r in self.races for u in r.unlisted for t in u.pm_tokens)
        return tokens

    def kalshi_tickers(self) -> set[str]:
        tickers = {t for r in self.races for o in r.outcomes for t in o.kalshi_tickers}
        tickers.update(t for r in self.races for u in r.unlisted for t in u.kalshi_tickers)
        return tickers


_SIG_TITLE = re.compile(r"^Will the (Democratic|Republican|Independent) Party win the (.+?)\?$")
_PARTY_WORD = {"Democratic": Party.D, "Republican": Party.R, "Independent": Party.I}


class ParsedTitle(msgspec.Struct, frozen=True):
    party: Party
    kind: Kind
    key: str
    name: str
    state: str | None = None
    district: int | None = None


def race_key(
    kind: Kind,
    state: str | None = None,
    district: int | None = None,
    chamber: str | None = None,
) -> str:
    if kind is Kind.CTRL:
        return f"CTRL-{chamber}"
    if kind is Kind.HOUSE:
        return f"HOUSE-{state}-{district:02d}"
    return f"{kind.value}-{state}"


def parse_sig_title(title: str) -> ParsedTitle | None:
    match = _SIG_TITLE.match(title.strip())
    if not match:
        return None
    party = _PARTY_WORD[match.group(1)]
    race = match.group(2)
    if race in ("U.S. House", "U.S. Senate"):
        chamber = race.split()[-1].upper()
        return ParsedTitle(party, Kind.CTRL, race_key(Kind.CTRL, chamber=chamber), race)
    house = re.match(r"^([A-Z]{2})-(\d{1,2}) House race$", race)
    if house:
        state, district = house.group(1), int(house.group(2))
        return ParsedTitle(
            party,
            Kind.HOUSE,
            race_key(Kind.HOUSE, state, district),
            f"{state}-{district:02d} House",
            state,
            district,
        )
    statewide = re.match(r"^(.+) (Senate|Governor)$", race)
    if statewide and statewide.group(1) in STATES:
        state = STATES[statewide.group(1)]
        kind = Kind.SEN if statewide.group(2) == "Senate" else Kind.GOV
        return ParsedTitle(party, kind, race_key(kind, state), f"{state} {statewide.group(2)}", state)
    return None


def load_mapping(path: Path) -> Mapping:
    return msgspec.json.decode(path.read_bytes(), type=Mapping)


def validate_against_sig(mapping: Mapping, markets: Iterable[m.Market]) -> list[str]:
    """Return a list of problems (empty = OK). Unmapped SIG markets are reported, not fatal."""
    problems: list[str] = []
    live = {mk.id: mk for mk in markets}
    mapped_ids: set[str] = set()
    for race in mapping.races:
        for outcome in race.outcomes:
            mapped_ids.add(outcome.sig_market_id)
            mk = live.get(outcome.sig_market_id)
            if mk is None:
                problems.append(f"{race.key}/{outcome.party}: SIG market {outcome.sig_market_id} not found")
                continue
            if mk.title != outcome.sig_title:
                problems.append(f"{race.key}/{outcome.party}: title changed to {mk.title!r}")
            if not mk.exchanges or mk.exchanges[0].id != outcome.sig_exchange_id:
                problems.append(f"{race.key}/{outcome.party}: exchange id mismatch")
            if not outcome.pm_tokens and not outcome.kalshi_tickers:
                problems.append(f"{race.key}/{outcome.party}: no external price source")
    for mk_id, mk in live.items():
        if mk_id not in mapped_ids and mk.status == "open":
            problems.append(f"UNMAPPED SIG market {mk_id}: {mk.title}")
    return problems
